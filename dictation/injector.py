"""Insert transcribed text into whatever field currently has focus.

Two strategies:

  * "paste" (default): put the text on the clipboard and send ⌘V, then restore
    the previous clipboard. Fast, and — crucially for Spanish — inserts accented
    characters (á é í ó ú ñ ¿ ¡) reliably, which per-character typing mangles.

  * "type": synthesize each keystroke with pynput. Slower and less robust with
    accents, but useful in the rare app that ignores paste.

Clipboard hygiene (what used to go wrong):
  * the old code saved/restored only plain text, so a copied image, file or
    rich-text selection was wiped by every dictation — we now snapshot every
    item and type;
  * it restored blindly after 0.4 s, clobbering anything you copied meanwhile —
    we only restore if the clipboard still holds our text;
  * clipboard managers (Raycast, Paste, Alfred…) recorded every dictation — we
    tag it as transient/auto-generated (nspasteboard.org convention).

⌘V is posted as a raw CGEvent with ONLY the Command flag, so a modifier you are
still physically holding (e.g. Shift from a ⌃⇧ shortcut) can't turn it into
⌘⇧V "paste and match style" or something else.

Both require macOS Accessibility permission for the host process.
"""

import threading
import time

from AppKit import NSPasteboard, NSPasteboardItem, NSPasteboardTypeString

from .log import get_logger

log = get_logger()

_V_KEYCODE = 9
_TRANSIENT_TYPES = ("org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType")
RESTORE_DELAY = 0.6   # slow Electron apps read the pasteboard after the keystroke


def _snapshot(pb):
    """Copy every item/type currently on the pasteboard."""
    items = []
    try:
        for item in pb.pasteboardItems() or []:
            entry = []
            for t in item.types() or []:
                try:
                    data = item.dataForType_(t)
                except Exception:
                    data = None
                if data is not None:
                    entry.append((t, data))
            if entry:
                items.append(entry)
    except Exception:
        log.exception("could not snapshot clipboard")
    return items


def _restore(pb, items):
    pb.clearContents()
    if not items:
        return
    objs = []
    for entry in items:
        it = NSPasteboardItem.alloc().init()
        for t, data in entry:
            it.setData_forType_(data, t)
        objs.append(it)
    pb.writeObjects_(objs)


def _write_text(pb, text, transient):
    pb.clearContents()
    item = NSPasteboardItem.alloc().init()
    item.setString_forType_(text, NSPasteboardTypeString)
    if transient:
        for t in _TRANSIENT_TYPES:
            item.setString_forType_("", t)
    pb.writeObjects_([item])


def _post_cmd_v():
    from Quartz import (CGEventCreateKeyboardEvent, CGEventPost, CGEventSetFlags,
                        CGEventSourceCreate, kCGEventFlagMaskCommand, kCGHIDEventTap,
                        kCGEventSourceStatePrivate)
    src = CGEventSourceCreate(kCGEventSourceStatePrivate)
    for down in (True, False):
        ev = CGEventCreateKeyboardEvent(src, _V_KEYCODE, down)
        CGEventSetFlags(ev, kCGEventFlagMaskCommand)
        CGEventPost(kCGHIDEventTap, ev)
        time.sleep(0.01)


class TextInjector:
    def __init__(self, mode: str = "paste", type_delay: float = 0.0025):
        self.mode = mode
        self.type_delay = type_delay
        self._kb = None

    def insert(self, text: str, keep_on_clipboard: bool = False) -> None:
        """Insert at the cursor. keep_on_clipboard=True leaves the dictation on
        the clipboard afterwards (used when there may be no text field)."""
        if not text:
            return
        try:
            if self.mode == "type":
                self._insert_by_typing(text)
                if keep_on_clipboard:
                    self.copy(text)
            else:
                self._insert_by_paste(text, keep_on_clipboard)
            log.info(f"injected {len(text)} chars via {self.mode}"
                     f"{' (kept on clipboard)' if keep_on_clipboard else ''}")
        except Exception:
            # Almost always missing Accessibility permission.
            log.exception("text injection failed (grant Accessibility permission?)")
            raise

    def copy(self, text: str) -> None:
        """Put text on the clipboard without pasting (History / "copy last"),
        so it stays there for a manual ⌘V."""
        if text:
            _write_text(NSPasteboard.generalPasteboard(), text, transient=False)

    def _insert_by_typing(self, text: str) -> None:
        from pynput import keyboard
        if self._kb is None:
            self._kb = keyboard.Controller()
        for ch in text:
            try:
                self._kb.type(ch)
                time.sleep(self.type_delay)
            except Exception:
                continue  # one unsupported glyph shouldn't abort the whole insert

    def _insert_by_paste(self, text: str, keep: bool) -> None:
        pb = NSPasteboard.generalPasteboard()
        saved = None if keep else _snapshot(pb)
        _write_text(pb, text, transient=not keep)
        ours = pb.changeCount()
        _post_cmd_v()

        if keep:
            return

        def _later():
            time.sleep(RESTORE_DELAY)
            try:
                if pb.changeCount() == ours:   # you didn't copy anything meanwhile
                    _restore(pb, saved)
            except Exception:
                log.exception("could not restore clipboard")

        threading.Thread(target=_later, daemon=True).start()
